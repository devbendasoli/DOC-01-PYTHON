

nome = "marcelo"
print(f"Parabéns, {nome.capitalize()}!")
# Saída: Parabéns, Marcelo!

#Como a variável nome estava toda em letras minúsculas ("marcelo"), o .capitalize() pegou a letra m e a transformou em M maiúscula ("Marcelo"), garantindo que o nome fique formatado corretamente, independentemente de como foi digitado originalmente.

