print("\nFunções built-in para listas em Python")
valores = [10, 20, 30, 40]
print("Lista de valores:", valores)

print("-----")
print("# len(): Quantidade de itens")
print("lista de valores:", valores)
print("Quantidade de itens (len):", len(valores))

print("-----")
print("# sum(): Soma de todos os números")
print("lista de valores:", valores)
print("Soma total (sum):", sum(valores))

print("-----")
print("# min() e max(): Menor e maior valor")
print("lista de valores:", valores)
print("Menor valor (min):", min(valores))
print("Maior valor (max):", max(valores))

