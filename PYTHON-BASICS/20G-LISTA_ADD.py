
print("-----")
print("Inio do COD")
print("\n# adição de elementos em uma lista:")
numeros = [10, 20]
print("Lista inicial:", numeros)
print("-----")

print("\n# append(): Adiciona no final")
numeros.append(30)
print("Após append(30):", numeros)
print("-----")

print("\n# insert(): Insere na posição escolhida (posição 1, valor 15)")
numeros.insert(1, 15)
print("Após insert(1, 15):", numeros)
print("-----")

print("\n# extend(): Adiciona vários itens no final")
numeros.extend([40, 50])
print("Após extend([40, 50]):", numeros)

print("FIM DE COD")
print("-----")