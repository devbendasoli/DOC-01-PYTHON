numeros = [10, 20, 30, 40, 50]
print("Lista original:", numeros)
print("Tamanho da lista:", len(numeros))
print("Índice do elemento 30:", numeros.index(30))

print("-----")
print("\n# Pega o primeiro elemento (índice 0)")
primeiro = numeros[0]
print("Primeiro elemento:", primeiro)

print("-----")
print("\n# Pega o último elemento (índice -1)")
ultimo = numeros[-1]
print("Último elemento:", ultimo)

print("-----")
print("\n# Pega uma fatia da lista (índices 1 a 3)")
fatia = numeros[1:4]
print("Fatia de 1 a 3:", fatia)

print("-----")
print("\n# Inverte a lista completa")
invertida = numeros[::-1]
print("Lista invertida:", invertida)
print("FInal do COD")
