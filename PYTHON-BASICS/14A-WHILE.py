# Loop FOR: repetir um número fixo de vezes (0 a 4)
for i in range(5):
    print(f"Número: {i}")
#Sai do loop quando i = 4

print("-----------")
# Loop FOR: percorrer uma lista
frutas = ["maçã", "banana", "laranja"]
for fruta in frutas:
    print(fruta)
#Sai do loop quando todas as 
# frutas foram percorridas

print("-----------")
# Loop WHILE: repete enquanto a 
# condição for verdadeira
contador = 0
while contador < 3:
    print(f"Contador: {contador}")
    contador += 1
#Saida do loop quando contador = 3

print("FIM DO PROGRAMA")    
