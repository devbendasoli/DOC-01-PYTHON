

# Loop FOR: repetir um número fixo de vezes (0 a 4)
for i in range(5):
    print(f"Número: {i}")

# Loop FOR: percorrer uma lista
frutas = ["maçã", "banana", "laranja"]
for fruta in frutas:
    print(fruta)

# Loop WHILE: repete enquanto a condição for verdadeira
contador = 0
while contador < 3:
    print(f"Contador: {contador}")
    contador += 1
    




