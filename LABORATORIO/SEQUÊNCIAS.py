

# 4. SEQUENCE FUNCTIONS (SEQUÊNCIAS)
print("\n--- 4. Sequências ---")
lista = ["A", "B", "C"]
print(f"len: {len(lista)}")
print(f"sorted: {sorted(['c', 'a', 'b'])}")
print(f"reversed: {list(reversed(lista))}")
print(f"enumerate: {list(enumerate(lista))}")
print(f"zip: {list(zip(['a', 'b'], [1, 2]))}")